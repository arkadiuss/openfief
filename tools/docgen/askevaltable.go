// The files the guide's results table reads besides the results: the bench's
// history, which counts D-221's consecutive passes, and the comments a person
// writes beside a row. Both are curated state of the bench, so they live with
// it in tools/askbench; the guide covers that folder.
const (
	historyFile  = "tools/askbench/history.json"
	commentsFile = "tools/askbench/comments.yaml"
	guideFile    = "docs/guides/ask-box-evaluation.md"
	// tableBegin and tableEnd fence the generated table in the guide. The guide
	// is mounted into the site unchanged and also read on GitHub, so the table
	// is written into the file, and `askeval table -check` (part of docs:gen)
	// fails the build when the text between the fences is not what the
	// committed results make.
	tableBegin = "<!-- ask-eval-table:begin (generated by `task ask:table`; do not edit) -->"
	tableEnd   = "<!-- ask-eval-table:end -->"
	// safetyCases is how many cases the bench tags safety (D-220); a result
	// file lists only the cases that failed, so the total is a constant, which
	// TestSafetyCasesMatchTheBenchsCases keeps equal to the bench's own cases.
	safetyCases = 9
	tagSafety   = "safety"
	// defaultRouting is what the table shows as the host of a model that is
	// not pinned to one.
	defaultRouting = "default routing"
)

var errNoFence = errors.New("the guide lacks a fence line of its results table")

// notAvailable is what a cell shows for a figure a row has none of.
const notAvailable = "n/a"

var errTableStale = errors.New("the guide's results table is stale: run `task ask:table` and commit the guide")

// void reports whether the run says nothing of the model: the bench's own fault
// ended some of its runs, no call of it got an answer, or it has no D-220
// verdict (it ran before the verdict existed). The
// results page marks such a run "void", and the guide's table leaves it out.
func (r *evalResult) void() bool { return r.Void > 0 || !r.Answered || r.Verdict == verdictNone }

// stands reports whether the run counts for a model's standing: a full run
// that is not void.
func (r *evalResult) stands() bool { return r.full() && !r.void() }

// casesPassed is how many of the run's cases cleared their bar.
func (r *evalResult) casesPassed() int { return r.Cases - len(r.Failing) }

// safetyPassed is how many safety cases cleared their bar.
func (r *evalResult) safetyPassed() int {
	missed := 0
	for _, f := range r.Failing {
		if f.Tag == tagSafety {
			missed++
		}
	}
	return safetyCases - missed
}

// historyLabel is the key of the run's model@host in the bench's history: the
// model id, then "@" and its host, or "(default routing)".
func (r *evalResult) historyLabel() string {
	if r.Host == "" {
		return r.Model + " (default routing)"
	}
	return r.Model + "@" + r.Host
}

// historyEntry is the part of a history entry the streak reads.
type historyEntry struct {
	Verdict     string `json:"verdict"`
	Reliability string `json:"reliability"`
	ConfigHash  string `json:"configHash"`
}

func (e *historyEntry) passed() bool { return e.Verdict == verdictPass && e.Reliability == verdictPass }

// evalHistory is the bench's history, by model@host label, oldest run first.
type evalHistory map[string][]historyEntry

// loadHistory reads the bench's history; a repository without one has none.
func loadHistory(repo fs.FS) (evalHistory, error) {
	data, err := fs.ReadFile(repo, historyFile)
	if errors.Is(err, fs.ErrNotExist) {
		return evalHistory{}, nil
	}
	if err != nil {
		return nil, fmt.Errorf("read %s: %w", historyFile, err)
	}
	var file struct {
		Runs evalHistory `json:"runs"`
	}
	if err := json.Unmarshal(data, &file); err != nil {
		return nil, fmt.Errorf("decode %s: %w", historyFile, err)
	}
	return file.Runs, nil
}

// consecutivePasses is how many of a model@host's newest runs in a row passed
// on the latest run's configuration (the bench's StreakOf, D-221): zero when
// the latest run did not pass, and ok is false for a label with no history.
func (h evalHistory) consecutivePasses(label string) (int, bool) {
	runs := h[label]
	if len(runs) == 0 {
		return 0, false
	}
	last := &runs[len(runs)-1]
	if !last.passed() {
		return 0, true
	}
	passes := 0
	for i := len(runs) - 1; i >= 0; i-- {
		if runs[i].ConfigHash != last.ConfigHash || !runs[i].passed() {
			break
		}
		passes++
	}
	return passes, true
}

// evalComments are the one-line comments a person wrote beside rows, keyed by
// "model@host" (the host as in the results, or only its provider slug before
// the "/") or by the model alone.
type evalComments map[string]string

// loadComments reads the comments file; a repository without one has none.
func loadComments(repo fs.FS) (evalComments, error) {
	data, err := fs.ReadFile(repo, commentsFile)
	if errors.Is(err, fs.ErrNotExist) {
		return evalComments{}, nil
	}
	if err != nil {
		return nil, fmt.Errorf("read %s: %w", commentsFile, err)
	}
	var file struct {
		Comments evalComments `yaml:"comments"`
	}
	if err := yaml.Unmarshal(data, &file); err != nil {
		return nil, fmt.Errorf("decode %s: %w", commentsFile, err)
	}
	return file.Comments, nil
}

// of is the comment for a result: the most specific key wins, the full
// model@host, then the model@provider slug, then the model alone. A row with
// none has an empty comment.
func (c evalComments) of(r *evalResult) string {
	keys := []string{r.label()}
	if provider, _, found := strings.Cut(r.Host, "/"); found {
		keys = append(keys, r.Model+"@"+provider)
	}
	keys = append(keys, r.Model)
	for _, k := range keys {
		if text := strings.TrimSpace(c[k]); text != "" {
			return text
		}
	}
	return ""
}

// standingRuns picks each model@host's latest run that stands (full and not
// void) from results, newest first, and orders them for the table: passing
// runs first, then more cases passed, then the cheaper, then by name.
func standingRuns(results []evalResult) []*evalResult {
	seen := map[string]bool{}
	var rows []*evalResult
	for i := range results {
		r := &results[i]
		if !r.stands() || seen[r.label()] {
			continue
		}
		seen[r.label()] = true
		rows = append(rows, r)
	}
	slices.SortStableFunc(rows, func(a, b *evalResult) int {
		switch {
		case (a.Verdict == verdictPass) != (b.Verdict == verdictPass):
			if a.Verdict == verdictPass {
				return -1
			}
			return 1
		case a.casesPassed() != b.casesPassed():
			return b.casesPassed() - a.casesPassed()
		}
		if c := compareCost(a, b); c != 0 {
			return c
		}
		return strings.Compare(a.label(), b.label())
	})
	return rows
}

// compareCost orders the cheaper run first and a run with no cost last.
func compareCost(a, b *evalResult) int {
	fa, errA := strconv.ParseFloat(a.CostPer1k, 64)
	fb, errB := strconv.ParseFloat(b.CostPer1k, 64)
	switch {
	case errA == nil && errB == nil:
		switch {
		case fa < fb:
			return -1
		case fa > fb:
			return 1
		}
		return 0
	case errA == nil:
		return -1
	case errB == nil:
		return 1
	}
	return 0
}

// resultsTable is the guide's table: one row per model@host.
func resultsTable(results []evalResult, history evalHistory, comments evalComments) string {
	var b strings.Builder
	b.WriteString("| Model | Host | Verdict | Cases passed | Safety | Reliability | USD per 1k questions | Consecutive passes | Last run | Comment |\n")
	b.WriteString("|---|---|---|---|---|---|---|---|---|---|\n")
	for _, r := range standingRuns(results) {
		host := r.Host
		if host == "" {
			host = defaultRouting
		}
		streak := notAvailable
		if n, ok := history.consecutivePasses(r.historyLabel()); ok {
			streak = strconv.Itoa(n)
		}
		cells := []string{
			tableCell(r.Model), tableCell(host), verdictText(r),
			fmt.Sprintf("%d/%d", r.casesPassed(), r.Cases), fmt.Sprintf("%d/%d", r.safetyPassed(), safetyCases),
			reliabilityPercent(r), costText(r), streak,
			r.Date + " (run " + r.Run + ")", tableCell(comments.of(r)),
		}
		b.WriteString("| " + strings.Join(cells, " | ") + " |\n")
	}
	return b.String()
}

// reliabilityPercent is the share of the run's questions the host failed
// (D-207; of its calls in a result before scorer version 3), marked when it
// fails the run.
func reliabilityPercent(r *evalResult) string {
	rel := r.Reliability
	if rel == nil {
		return "not recorded"
	}
	text := fmt.Sprintf("%.1f%%", rel.Rate*percentFactor)
	if rel.Failed {
		text += " (fails)"
	}
	return text
}

// withTable returns guide with the text between its fences replaced by table.
func withTable(guide, table string) (string, error) {
	head, rest, found := strings.Cut(guide, tableBegin)
	if !found {
		return "", fmt.Errorf("%w: %s", errNoFence, tableBegin)
	}
	_, tail, found := strings.Cut(rest, tableEnd)
	if !found {
		return "", fmt.Errorf("%w: %s", errNoFence, tableEnd)
	}
	return head + tableBegin + "\n\n" + table + "\n" + tableEnd + tail, nil
}

// runAskEvalTable handles `docgen askeval table`: it rewrites the guide's
// results table from the committed results, the history and the comments, or
// with -check only fails when the guide's table is not what they make.
func runAskEvalTable(repo fs.FS, args []string, stdout io.Writer) error {
	flags := flag.NewFlagSet("askeval table", flag.ContinueOnError)
	check := flags.Bool("check", false, "fail when the guide's table is stale instead of rewriting it")
	if err := flags.Parse(args); err != nil {
		return fmt.Errorf("askeval table: %w", err)
	}
	guide, err := guideWithTable(repo)
	if err != nil {
		return err
	}
	switch {
	case guide.want == guide.current:
		_, err = fmt.Fprintln(stdout, "askeval: the guide's results table is current")
	case *check:
		return errTableStale
	default:
		if err = os.WriteFile(guideFile, []byte(guide.want), filePerm); err != nil {
			return fmt.Errorf("write guide: %w", err)
		}
		_, err = fmt.Fprintln(stdout, "askeval: rewrote the guide's results table")
	}
	if err != nil {
		return fmt.Errorf("write summary: %w", err)
	}
	return nil
}

// guideText is the guide as committed and as the results make it.
type guideText struct{ current, want string }

// guideWithTable reads the guide and returns it with the text of its results
// table as the committed results, history and comments make it.
func guideWithTable(repo fs.FS) (guideText, error) {
	results, err := loadResults(repo)
	if err != nil {
		return guideText{}, err
	}
	history, err := loadHistory(repo)
	if err != nil {
		return guideText{}, err
	}
	comments, err := loadComments(repo)
	if err != nil {
		return guideText{}, err
	}
	data, err := fs.ReadFile(repo, guideFile)
	if err != nil {
		return guideText{}, fmt.Errorf("read guide: %w", err)
	}
	want, err := withTable(string(data), resultsTable(results, history, comments))
	return guideText{current: string(data), want: want}, err
}
