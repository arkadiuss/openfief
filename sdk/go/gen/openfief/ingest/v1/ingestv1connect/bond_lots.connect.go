// OpenFief's manual treasury bond lot entry contract (docs/DESIGN.md D-9,
// D-49).
//
// The owner enters Polish retail treasury bond lots by hand in the built-in
// UI, which hands each to the core (D-49). The core hands it to the
// connector instance bound to the account, through the connector contract's
// ImportBondLots (proto/openfief/connector/v1/connector.proto), and imports
// what that connector delivers as one import batch, like any other: data
// enters the ledger only through a connector's ingest path (D-7). The core
// serves BondLotService to VIEW plugins only, next to the AuthService. It
// is not part of the public read API (D-6), which stays read-only.
//
// Calling conventions are the AuthService's
// (proto/openfief/identity/v1/auth.proto) and the ModelPortfolioService's
// (proto/openfief/portfolio/v1/model.proto):
// - Every call carries the view plugin's projected ServiceAccount token
//   (audience openfief-core, D-27) as "Authorization: Bearer <token>"; a
//   call without one, or from a plugin that is not a view plugin, fails
//   with PERMISSION_DENIED.
// - Every request carries origin and the owner's session_token. A missing,
//   unknown, expired or revoked session fails with UNAUTHENTICATED; a
//   read-scoped session, or an origin off the core's allow-list, fails with
//   PERMISSION_DENIED.
// - A lot that breaks a rule (an unknown series code, a purchase date that
//   doesn't match the series or lies in the future, a quantity that is not
//   a positive whole number, malformed terms) fails with INVALID_ARGUMENT
//   naming the rule, and nothing is imported.
// - Deleting a lot that was never entered fails with INVALID_ARGUMENT, and
//   nothing is imported.
// - An account with no connector instance bound to it, or with more than
//   one, fails with FAILED_PRECONDITION; so does a bound connector that
//   takes no bond lots. A connector that can't be reached fails with
//   UNAVAILABLE, and the owner may simply send the lot again.

