// ReadServiceHandler is an implementation of the openfief.views.v1.ReadService service.
type ReadServiceHandler interface {
	// ListSleeves returns every sleeve, in ID order.
	ListSleeves(context.Context, *connect.Request[v1.ListSleevesRequest]) (*connect.Response[v1.ListSleevesResponse], error)
	// ListSleeveKinds returns every sleeve kind, in key order (D-71).
	ListSleeveKinds(context.Context, *connect.Request[v1.ListSleeveKindsRequest]) (*connect.Response[v1.ListSleeveKindsResponse], error)
	// ListAccounts returns every account, in ID order.
	ListAccounts(context.Context, *connect.Request[v1.ListAccountsRequest]) (*connect.Response[v1.ListAccountsResponse], error)
	// ListConnectorBindings returns every connector binding: which connector
	// instance may write to which account, in instance then account order.
	ListConnectorBindings(context.Context, *connect.Request[v1.ListConnectorBindingsRequest]) (*connect.Response[v1.ListConnectorBindingsResponse], error)
	// ListBrokerAccounts returns the broker accounts connector instances
	// reported (D-72), in instance then ID order, each with the account it is
	// mapped to. Nothing of an unmapped broker account is booked.
	ListBrokerAccounts(context.Context, *connect.Request[v1.ListBrokerAccountsRequest]) (*connect.Response[v1.ListBrokerAccountsResponse], error)
	// GetAccount returns one account.
	GetAccount(context.Context, *connect.Request[v1.GetAccountRequest]) (*connect.Response[v1.GetAccountResponse], error)
	// ListTransactions returns one page of the current version of each of an
	// account's transactions, in date then key order. Superseded versions are
	// left out.
	ListTransactions(context.Context, *connect.Request[v1.ListTransactionsRequest]) (*connect.Response[v1.ListTransactionsResponse], error)
	// ListHoldings returns an account's non-zero holdings at the end of a date,
	// in ISIN then venue symbol order.
	ListHoldings(context.Context, *connect.Request[v1.ListHoldingsRequest]) (*connect.Response[v1.ListHoldingsResponse], error)
	// ListLots returns an account's open tax lots at the end of a date, per
	// instrument, oldest first.
	ListLots(context.Context, *connect.Request[v1.ListLotsRequest]) (*connect.Response[v1.ListLotsResponse], error)
	// ListCash returns an account's non-zero cash at the end of a date, one
	// balance per currency, in currency order.
	ListCash(context.Context, *connect.Request[v1.ListCashRequest]) (*connect.Response[v1.ListCashResponse], error)
	// ListAssertionChecks returns an account's balance assertions with the
	// result of their latest check, in date then ledger account order. A
	// flagged check is an error for the owner to resolve.
	ListAssertionChecks(context.Context, *connect.Request[v1.ListAssertionChecksRequest]) (*connect.Response[v1.ListAssertionChecksResponse], error)
	// ListAccountValuations returns an account's stored valuations in a date
	// range, with their totals per date.
	ListAccountValuations(context.Context, *connect.Request[v1.ListAccountValuationsRequest]) (*connect.Response[v1.ListAccountValuationsResponse], error)
	// GetValuationStatus returns the date an account is valued through and
	// whether a revaluation is pending or running (D-36).
	GetValuationStatus(context.Context, *connect.Request[v1.GetValuationStatusRequest]) (*connect.Response[v1.GetValuationStatusResponse], error)
	// ListValuationTotals returns the whole portfolio's value per date in a
	// date range, summed over every account's stored valuations.
	ListValuationTotals(context.Context, *connect.Request[v1.ListValuationTotalsRequest]) (*connect.Response[v1.ListValuationTotalsResponse], error)
	// ListValuationStatuses returns every account's valuation status, in
	// account ID order.
	ListValuationStatuses(context.Context, *connect.Request[v1.ListValuationStatusesRequest]) (*connect.Response[v1.ListValuationStatusesResponse], error)
	// ListPriceChecks returns every institution's own price, such as IBKR's
	// mark price, compared with the latest stored price of its instrument on
	// or before its date (D-22, D-111), in date, instrument and cross-check
	// source order, each with the threshold it was flagged at (D-110) and
	// whether the owner acknowledged it (D-112). A flagged check is for the
	// owner to look at; it changes no price or valuation.
	ListPriceChecks(context.Context, *connect.Request[v1.ListPriceChecksRequest]) (*connect.Response[v1.ListPriceChecksResponse], error)
	// GetAllocation returns the portfolio's value on a date in the reporting
	// currency, split by asset class, currency, institution or sleeve (D-30).
	// Holdings count at their stored valuation on the date and cash at the FX
	// rate for the date; holdings without a valuation are listed as unvalued.
	GetAllocation(context.Context, *connect.Request[v1.GetAllocationRequest]) (*connect.Response[v1.GetAllocationResponse], error)
	// GetPerformance returns the portfolio's time-weighted return per day
	// (D-61) as an index that starts at 100, with the portfolio's value
	// including cash, in the reporting currency. Deposits and withdrawals are
	// not performance; transfers between the owner's own accounts are not cash
	// flows. The series stops at the last day every account is valued for,
	// and says why.
	GetPerformance(context.Context, *connect.Request[v1.GetPerformanceRequest]) (*connect.Response[v1.GetPerformanceResponse], error)
	// GetModelPortfolio returns the model portfolio (D-52) with its backtest
	// (D-53) as an index that starts at 100 on go-live, like the
	// performance series, and the max drawdown of the model and of each
	// target (D-54), in the reporting currency. While the model portfolio is
	// off it fails with NOT_FOUND and says nothing about it.
	GetModelPortfolio(context.Context, *connect.Request[v1.GetModelPortfolioRequest]) (*connect.Response[v1.GetModelPortfolioResponse], error)
	// ListPlugins returns the installed plugin instances (D-46, D-48), in
	// name order, each with what it may do and how far its image's signature
	// is trusted (D-56), as the operator recorded them. It only reads: nothing
	// in this API installs, removes or approves a plugin. It fails with
	// UNAVAILABLE when the core can't read the cluster.
	ListPlugins(context.Context, *connect.Request[v1.ListPluginsRequest]) (*connect.Response[v1.ListPluginsResponse], error)
}

