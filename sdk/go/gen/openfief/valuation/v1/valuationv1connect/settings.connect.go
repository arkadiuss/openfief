// OpenFief's owner settings contract (docs/DESIGN.md D-62, D-78, D-79,
// D-113, D-167).
//
// The owner's settings that are not an account's terms: the number format
// the built-in UI writes amounts in (D-113), shown next to the reporting
// currency (D-62), the owner's marginal personal income tax rate, which
// taxes an early withdrawal from IKZE (D-78), and the charts' start the
// owner chose (D-138), the portfolio's and each account's (D-167). The
// read API serves the reporting currency and the number format to any
// reader (ReadService.GetSettings), and the charts' start the owner chose
// with the performance (ReadService.GetPerformance); this service is the
// owner's entry service for changing them (D-79).
//
// The core serves SettingsService to VIEW plugins only, next to the
// AuthService. Calling conventions are the AuthService's
// (proto/openfief/identity/v1/auth.proto):
// - Every call carries the view plugin's projected ServiceAccount token
//   (audience openfief-core, D-27) as "Authorization: Bearer <token>"; a
//   call without one, or from a plugin that is not a view plugin, fails
//   with PERMISSION_DENIED.
// - Every request carries origin and the owner's session_token. A missing,
//   unknown, expired or revoked session fails with UNAUTHENTICATED; a
//   read-scoped session, or an origin off the core's allow-list, fails with
//   PERMISSION_DENIED.
// - A number format key that is not one of number_formats, a marginal rate
//   that is not a decimal above 0 and below 1, or a charts' start that is
//   not a YYYY-MM-DD date, fails with INVALID_ARGUMENT and nothing changes.
// - SetEarlyRedemptionFee for an ISIN whose series terms are not stored
//   fails with NOT_FOUND; without a fee, for a series whose fee is not
//   assumed, with FAILED_PRECONDITION; a fee that is not a decimal of zero
//   or more, with INVALID_ARGUMENT. Nothing changes then.
// - A charts' start of an account the owner may not change (D-163) fails
//   with PERMISSION_DENIED, whether it is stored or not; one of an account
//   that is not stored, with NOT_FOUND.

