// OpenFief's price check contract (docs/DESIGN.md D-110, D-112, D-79).
//
// A price check compares an institution's own price of an instrument, a
// cross-check price such as IBKR's mark price, with the latest stored price
// of the instrument on or before its date (D-111). It is flagged when the
// two differ by more than 1% of the stored price, in either direction,
// unless the owner set another threshold for the instrument (D-110). The
// owner can acknowledge a flagged check; each acknowledgement is recorded
// append-only and covers the check only while both prices stay the same
// (D-112). The read API lists the checks (ListPriceChecks in
// proto/openfief/views/v1/read_service.proto).
//
// The core serves PriceCheckService to VIEW plugins only, next to the
// AuthService, as the owner's entry service for this kind of entry (D-79).
// Calling conventions are the AuthService's
// (proto/openfief/identity/v1/auth.proto):
// - Every call carries the view plugin's projected ServiceAccount token
//   (audience openfief-core, D-27) as "Authorization: Bearer <token>"; a
//   call without one, or from a plugin that is not a view plugin, fails
//   with PERMISSION_DENIED.
// - Every request carries origin and the owner's session_token. A missing,
//   unknown, expired or revoked session fails with UNAUTHENTICATED; a
//   read-scoped session, or an origin off the core's allow-list, fails with
//   PERMISSION_DENIED.
// - A request without an instrument, a threshold that isn't a decimal
//   fraction greater than 0 and less than 1, a malformed date, or an
//   acknowledgement of a check that isn't flagged fails with
//   INVALID_ARGUMENT and nothing changes; an acknowledgement of a check
//   that doesn't exist fails with NOT_FOUND.

