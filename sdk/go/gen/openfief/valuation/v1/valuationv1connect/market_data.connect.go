// OpenFief's market-data sources contract (docs/DESIGN.md D-94, D-124,
// D-79).
//
// Each series of market data, one instrument's prices, one currency's FX
// rates to PLN or one period index's readings (CPI, the NBP reference
// rate), takes every value from exactly one source: a connector instance
// that delivered values of its kind (D-48, D-124). The source is chosen
// from the owner's ranking of that kind's sources when the series first
// needs a value, the highest-ranked source with a value of it, and the
// owner can change it for that one series. A day without a value takes the
// series' latest earlier one, never another source's; every other
// source's values are stored as cross-checks (D-22). A series whose source
// has had no value for longer than the kind's gap threshold raises an
// attention item (D-130). By default the first-party connector of each
// kind ranks first: EODHD for prices, NBP for FX rates, and the treasury
// bond connector for CPI and the NBP reference rate; the other sources
// follow by name. Market index levels, such as WIG20's, have no ranking
// and no series source: each index and date keeps the level delivered last
// (D-124).
//
// The core serves MarketDataService to VIEW plugins only, next to the
// AuthService, as the owner's entry service for this kind of entry (D-79).
// Calling conventions are the AuthService's
// (proto/openfief/identity/v1/auth.proto):
// - Every call carries the view plugin's projected ServiceAccount token
//   (audience openfief-core, D-27) as "Authorization: Bearer <token>"; a
//   call without one, or from a plugin that is not a view plugin, fails
//   with PERMISSION_DENIED.
// - Every request carries origin and the owner's session_token. A missing,
//   unknown, expired or revoked session fails with UNAUTHENTICATED; a
//   read-scoped session, or an origin off the core's allow-list, fails with
//   PERMISSION_DENIED.
// - A ranking that names a source twice, or a source with an empty name or
//   one longer than 64 characters, or a kind that is unspecified, fails
//   with INVALID_ARGUMENT and nothing changes. So does a series whose key
//   names no instrument, no currency other than PLN or no index kind, a
//   series source without any value of the series, and a gap threshold
//   outside 1 to 3660 days.

