// OpenFief's model-portfolio maintainer contract (docs/DESIGN.md D-204).
//
// The maintainer is a role of the model router (D-205): OpenFief computes the
// model portfolio's weights and drift, a model writes a short note about them
// weekly and whenever the owner asks, and may propose changes to the targets,
// which wait in the Inbox for the owner to apply or dismiss. It has no
// trading tools, and applying a proposal changes the model portfolio's
// weights only: nothing trades.
//
// The core serves MaintainerService to VIEW plugins only, next to the
// ModelPortfolioService, and it is not part of the public read API (D-6).
// Calling conventions are the ModelPortfolioService's
// (proto/openfief/portfolio/v1/model.proto):
// - Every call carries the view plugin's projected ServiceAccount token as
//   "Authorization: Bearer <token>".
// - Every request carries origin and the person's session_token. A missing,
//   unknown, expired or revoked session fails with UNAUTHENTICATED.
// - GetMaintainer is for the owner and for any session that may view every
//   account (D-163), since the note speaks of the whole portfolio; a session
//   that may not fails with PERMISSION_DENIED. Every other call is the
//   owner's alone: a read-scoped session fails with PERMISSION_DENIED.
// - Nothing here carries an amount: weights are percent of the portfolio, as
//   decimal strings.

