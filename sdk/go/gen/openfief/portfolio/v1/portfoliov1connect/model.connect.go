// OpenFief's model portfolio entry contract (docs/DESIGN.md D-52, D-49).
//
// The owner enters the model portfolio in the built-in UI, which hands it to
// the core (D-52: "like manual bond lots", D-49). The core serves
// ModelPortfolioService to VIEW plugins only, next to the AuthService. It is
// not part of the public read API (D-6), which stays read-only: the read
// API serves the model, its backtest and drawdowns only while it is on.
//
// Calling conventions are the AuthService's
// (proto/openfief/identity/v1/auth.proto):
// - Every call carries the view plugin's projected ServiceAccount token
//   (audience openfief-core, D-27) as "Authorization: Bearer <token>"; a
//   call without one, or from a plugin that is not a view plugin, fails
//   with PERMISSION_DENIED.
// - Every request carries origin and the owner's session_token. A missing,
//   unknown, expired or revoked session fails with UNAUTHENTICATED; a
//   read-scoped session, or an origin off the core's allow-list, fails with
//   PERMISSION_DENIED. Only an owner-scoped session may read or change the
//   model here, whether it is on or off.
// - A model that breaks a rule (weights not summing to 100%, a target
//   twice, an index without a currency, a malformed ISIN) fails with
//   INVALID_ARGUMENT and nothing is stored.

