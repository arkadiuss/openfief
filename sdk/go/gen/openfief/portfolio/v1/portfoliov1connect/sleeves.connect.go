// OpenFief's sleeve entry contract (docs/DESIGN.md D-71, D-73, D-79).
//
// The owner adds and renames sleeve kinds and sleeves in the built-in UI, in
// the first-run wizard (D-73) and later, and the UI hands them to the core
// through SleeveService: one owner-only service for this kind of entry
// (D-79). The read API (D-6) stays read-only: it lists sleeves and sleeve
// kinds for any read caller.
//
// Calling conventions are the AuthService's
// (proto/openfief/identity/v1/auth.proto), as in model.proto:
// - Every call carries the view plugin's projected ServiceAccount token
//   (audience openfief-core, D-27) as "Authorization: Bearer <token>"; a
//   call without one, or from a plugin that is not a view plugin, fails
//   with PERMISSION_DENIED.
// - Every request carries origin and the owner's session_token. A missing,
//   unknown, expired or revoked session fails with UNAUTHENTICATED; a
//   read-scoped session, or an origin off the core's allow-list, fails with
//   PERMISSION_DENIED.
// - The owner names kinds and sleeves; the core makes their keys and IDs
//   from the names, as lowercase hyphenated words. A name the core can make
//   no key from, an unknown kind, or a role other than the kind's default
//   without role_override fails with INVALID_ARGUMENT and nothing is
//   stored; a name whose key or ID is taken fails with ALREADY_EXISTS; an
//   unknown kind or sleeve to change fails with NOT_FOUND.

