// OpenFief's attention item contract (docs/DESIGN.md D-130, D-131, D-79).
//
// Every check that needs the owner raises an attention item in one
// append-only store: its kind, its subject, its state (open, acknowledged
// or resolved) and its history, each change appended and never changed in
// place. At most one item stands for each kind and subject. The read API
// lists the items (ListAttentionItems in
// proto/openfief/views/v1/read_service.proto).
//
// The core serves AttentionService to VIEW plugins only, on its plugin
// port (D-115), as the owner's entry service for this kind of entry
// (D-79). Calling conventions are the AuthService's
// (proto/openfief/identity/v1/auth.proto):
// - Every call carries the view plugin's projected ServiceAccount token
//   (audience openfief-core, D-27) as "Authorization: Bearer <token>"; a
//   call without one, or from a plugin that is not a view plugin, fails
//   with PERMISSION_DENIED.
// - Every request carries origin and the owner's session_token. A missing,
//   unknown, expired or revoked session fails with UNAUTHENTICATED; a
//   read-scoped session, or an origin off the core's allow-list, fails with
//   PERMISSION_DENIED.
// - An item that doesn't exist fails with NOT_FOUND; acknowledging a
//   resolved item fails with FAILED_PRECONDITION, and so does resolving an
//   item of a kind that resolves only when its check clears. Nothing
//   changes then.
//
// Each change is also published as an AttentionItemChanged event from the
// core's outbox, written in the same database transaction as the change,
// so notifications and, in later milestones, agents can act on it.

