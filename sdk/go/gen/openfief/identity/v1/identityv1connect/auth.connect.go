// AuthServiceHandler is an implementation of the openfief.identity.v1.AuthService service.
type AuthServiceHandler interface {
	// GetLoginMethods says which ways in the login page can offer at origin.
	// It needs no session.
	GetLoginMethods(context.Context, *connect.Request[v1.GetLoginMethodsRequest]) (*connect.Response[v1.GetLoginMethodsResponse], error)
	// BeginRegistration starts creating a passkey on origin's host. It needs
	// either a valid one-time enrollment code issued for origin (D-60) or an
	// owner-scoped session issued on origin's host with a recent passkey
	// check (D-183).
	BeginRegistration(context.Context, *connect.Request[v1.BeginRegistrationRequest]) (*connect.Response[v1.BeginRegistrationResponse], error)
	// FinishRegistration verifies the new credential and stores the passkey.
	// A registration begun with an enrollment code uses the code up and also
	// logs the owner in: the response carries a new owner-scoped session.
	FinishRegistration(context.Context, *connect.Request[v1.FinishRegistrationRequest]) (*connect.Response[v1.FinishRegistrationResponse], error)
	// BeginLogin starts a passkey login on origin's host. It needs no session.
	BeginLogin(context.Context, *connect.Request[v1.BeginLoginRequest]) (*connect.Response[v1.BeginLoginResponse], error)
	// FinishLogin verifies the assertion against the passkeys of origin's
	// host and issues an owner-scoped session. A passkey whose signature
	// counter went backwards is refused (a cloned authenticator).
	FinishLogin(context.Context, *connect.Request[v1.FinishLoginRequest]) (*connect.Response[v1.FinishLoginResponse], error)
	// CreateDemoSession issues a read-scoped session without credentials. It
	// works only when the database carries the demo marker and the core runs
	// with --demo-sessions; otherwise it fails with PERMISSION_DENIED.
	CreateDemoSession(context.Context, *connect.Request[v1.CreateDemoSessionRequest]) (*connect.Response[v1.CreateDemoSessionResponse], error)
	// Logout revokes the session. Any scope.
	Logout(context.Context, *connect.Request[v1.LogoutRequest]) (*connect.Response[v1.LogoutResponse], error)
	// WhoAmI returns the owner and the session. Any scope.
	WhoAmI(context.Context, *connect.Request[v1.WhoAmIRequest]) (*connect.Response[v1.WhoAmIResponse], error)
	// ListPasskeys returns every passkey, on every host. Owner scope.
	ListPasskeys(context.Context, *connect.Request[v1.ListPasskeysRequest]) (*connect.Response[v1.ListPasskeysResponse], error)
	// RemovePasskey removes a passkey and revokes every session it signed in.
	// The last passkey can't be removed (FAILED_PRECONDITION). Owner scope,
	// with a recent passkey check (D-183).
	RemovePasskey(context.Context, *connect.Request[v1.RemovePasskeyRequest]) (*connect.Response[v1.RemovePasskeyResponse], error)
	// CreateScriptToken issues a read-only script token (D-27) and returns its
	// secret, the only time it is shown. Owner scope, with a recent passkey
	// check (D-183).
	CreateScriptToken(context.Context, *connect.Request[v1.CreateScriptTokenRequest]) (*connect.Response[v1.CreateScriptTokenResponse], error)
	// ListScriptTokens returns every script token, expired and revoked ones
	// included, in creation order. Owner scope.
	ListScriptTokens(context.Context, *connect.Request[v1.ListScriptTokensRequest]) (*connect.Response[v1.ListScriptTokensResponse], error)
	// RevokeScriptToken revokes a script token. Owner scope.
	RevokeScriptToken(context.Context, *connect.Request[v1.RevokeScriptTokenRequest]) (*connect.Response[v1.RevokeScriptTokenResponse], error)
	// CreateEnrollmentLink issues a one-time link for creating a passkey on
	// another allowed origin, such as the owner's own Ingress host (D-60).
	// Owner scope, with a recent passkey check (D-183).
	CreateEnrollmentLink(context.Context, *connect.Request[v1.CreateEnrollmentLinkRequest]) (*connect.Response[v1.CreateEnrollmentLinkResponse], error)
	// BeginPasskeyCheck starts a passkey check in the session: an assertion
	// like a login's, against the passkeys of origin's host (D-183). Owner
	// scope.
	BeginPasskeyCheck(context.Context, *connect.Request[v1.BeginPasskeyCheckRequest]) (*connect.Response[v1.BeginPasskeyCheckResponse], error)
	// FinishPasskeyCheck verifies the assertion and records the check on the
	// session, which may then enroll or remove a passkey, issue an enrollment
	// link and create a script token for five minutes. Owner scope.
	FinishPasskeyCheck(context.Context, *connect.Request[v1.FinishPasskeyCheckRequest]) (*connect.Response[v1.FinishPasskeyCheckResponse], error)
	// SignOutEverywhere revokes every session, on every host and of either
	// scope, the caller's own included (D-183). Owner scope.
	SignOutEverywhere(context.Context, *connect.Request[v1.SignOutEverywhereRequest]) (*connect.Response[v1.SignOutEverywhereResponse], error)
	// ListAuditEntries returns a page of the audit log (D-211), newest first,
	// filtered by actor, action and time. Owner scope only: a read-scoped
	// (demo) session is refused with PERMISSION_DENIED, and the log is not on
	// the read API (D-137), so no script token or view plugin reads it there.
	// Reading the log is itself no entry. An entry names who, what, which
	// records by ID, when and the outcome, never an amount, a secret or a
	// question's text (GR-12).
	ListAuditEntries(context.Context, *connect.Request[v1.ListAuditEntriesRequest]) (*connect.Response[v1.ListAuditEntriesResponse], error)
	// CreateGrant lets a script token or a view plugin view an account, a
	// sleeve or the whole household (D-209). A sleeve's grant covers the
	// accounts placed in it later, and the household's every account, present
	// and future. A grant only ever lets its holder view. The holder and the
	// target must exist: an unknown one is NOT_FOUND. Granting what is granted
	// already changes nothing and returns the grant in force. Each new grant is
	// an audit entry (D-211), written in the same transaction. Owner scope
	// only: a read-scoped (demo) session is refused with PERMISSION_DENIED,
	// and it is not on the read API, so no script token reads or changes it.
	// While the core runs with --authz=policy a grant is stored and has no
	// effect, since every holder of read access views every account then.
	CreateGrant(context.Context, *connect.Request[v1.CreateGrantRequest]) (*connect.Response[v1.CreateGrantResponse], error)
	// RevokeGrant ends a grant: from the next call its holder no longer views
	// what only that grant gave it. The grant stays in ListGrants, with its end,
	// as history. Revoking a grant already ended changes nothing; one that never
	// existed is NOT_FOUND. Each revocation is an audit entry. Owner scope.
	RevokeGrant(context.Context, *connect.Request[v1.RevokeGrantRequest]) (*connect.Response[v1.RevokeGrantResponse], error)
	// ListGrants returns the grants, oldest first, optionally of one holder
	// and optionally only those in force. Owner scope.
	ListGrants(context.Context, *connect.Request[v1.ListGrantsRequest]) (*connect.Response[v1.ListGrantsResponse], error)
}

