// OpenFief's authentication contract (docs/DESIGN.md D-26, D-27, D-60).
//
// The core serves AuthService to VIEW plugins only, such as the built-in
// UI, which acts as the backend for the owner's browser: browser <-> view
// plugin <-> core. It is not part of the public read API (D-6), which stays
// read-only.
//
// Authentication and the session are separate. An authenticator proves
// that the person at the browser is the owner, the only person an
// installation has (GR-2), and with what scope; the core then issues a
// session. M0 has two authenticators: passkeys (WebAuthn, D-26), which give
// an owner-scoped session, and the demo authenticator, which gives a
// read-scoped session without credentials, only on a demo database and only
// when the core runs with --demo-sessions.
//
// Calling conventions:
// - Every call carries the view plugin's projected ServiceAccount token
//   (audience openfief-core, D-27) as "Authorization: Bearer <token>". A
//   call without one, with an invalid one, or from a plugin that is not a
//   view plugin fails with PERMISSION_DENIED.
// - The owner's session token never travels in the Authorization header:
//   it is the session_token field of the request. The view plugin keeps it
//   in an HttpOnly, Secure (except on http://localhost), SameSite=Strict
//   cookie and presents it as the bearer token to the read API (/v1).
// - Every request carries origin: the origin the owner's browser uses,
//   scheme, host and port, such as "https://dev.openfief.dev" or
//   "http://localhost:8080". It must be on the core's allow-list
//   (OPENFIEF_AUTH_ORIGINS), or the call fails with PERMISSION_DENIED. Its host is
//   the WebAuthn relying party ID: a passkey works only on the host it was
//   created on (D-60), and a session only on the host it was issued on.
// - A missing, unknown, expired or revoked session fails with
//   UNAUTHENTICATED: the view plugin drops its cookie and shows the login.
//   A read-scoped session calling an owner-only method fails with
//   PERMISSION_DENIED.
// - Enrolling or removing a passkey, issuing an enrollment link and
//   creating a script token also need a passkey check made in the same
//   session within the last five minutes (D-183): logging in with a passkey
//   counts, and so does BeginPasskeyCheck then FinishPasskeyCheck. Without
//   one they fail with FAILED_PRECONDITION and a PasskeyCheckRequired error
//   detail: the view plugin asks the owner to confirm with their passkey,
//   runs the check and asks again.
// - WebAuthn options and credentials travel as JSON text in the WebAuthn
//   Level 3 JSON forms, so the browser uses
//   PublicKeyCredential.parseCreationOptionsFromJSON,
//   parseRequestOptionsFromJSON and credential.toJSON() unchanged.

