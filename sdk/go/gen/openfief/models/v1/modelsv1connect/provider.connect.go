// The model-provider contract (docs/DESIGN.md D-205): a model-provider plugin
// serves ModelProviderService and the core's model router calls it. A plugin
// speaks one wire protocol (OpenAI-compatible chat first, Anthropic's and
// Gemini's later) to one provider instance; its model entries come from its
// configuration. The core holds the router, the roles and the data tiers
// (D-206): the plugin never sees a role, a tier or who asked.
//
// Conventions for every message in this package:
//   - Prices are exact decimal strings of an ISO 4217 currency per million
//     tokens, never floating point.
//   - Text the core sends or receives (messages, answers, tool arguments)
//     is the owner's data: neither the plugin nor the core logs it or keeps
//     it (GR-12, D-211).
//   - The core authenticates every call with a short-lived ServiceAccount
//     token whose audience is "openfief-plugin:<instance>", in
//     "Authorization: Bearer <token>" (D-59). The Go SDK verifies it.
//   - A plugin reaches its provider only through the egress proxy, and only
//     the host its grant approves (D-32).
//   - A model that is not one of the plugin's entries, a message list that
//     is empty or ends with an assistant message, or a tool without a name
//     fails with INVALID_ARGUMENT. A provider that is down, slow or refuses
