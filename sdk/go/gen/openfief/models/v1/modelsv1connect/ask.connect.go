// The Ask box's model contract (docs/DESIGN.md D-203, D-205, D-206, D-211).
//
// With a model configured, the Ask box answers its fixed commands itself and
// sends anything else to the model through the core's model router. The
// built-in UI runs the tool loop, since the tools are its own read-only
// answerers and it reads with the asking person's session; the core holds
// the switch, the route and the data tiers, so every round goes through the
// router: AskModelService is the router's door for the Ask box's role, and
// nothing else. A view plugin can't name another role, and nothing here
// changes anything.
//
// The core serves AskModelService to VIEW plugins only, next to the
// ModelSettingsService. Calling conventions are the AuthService's
// (proto/openfief/identity/v1/auth.proto):
//   - Every call carries the view plugin's projected ServiceAccount token
//     (audience openfief-core, D-27) as "Authorization: Bearer <token>"; a
//     call without one, or from a plugin that is not a view plugin, fails
//     with PERMISSION_DENIED.
//   - Every request carries origin and the asking person's session_token. A
//     missing, unknown, expired or revoked session fails with
//     UNAUTHENTICATED. A read-scoped session may ask: what the model sees is
//     limited by what that session may read, which the plugin enforces by
//     reading with the session's own token, never its own.
//   - Text of messages, answers and tool arguments is the owner's data: the
//     core neither logs nor keeps it (GR-12, D-211). The audit log keeps the
//     role, the provider instance and model and a call ID, and nothing else.

