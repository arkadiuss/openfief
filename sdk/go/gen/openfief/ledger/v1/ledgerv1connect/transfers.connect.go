// OpenFief's transfer confirmation contract (docs/DESIGN.md D-105, D-79).
//
// Money the owner moves between two of their own accounts arrives as a
// withdrawal in one and a deposit in the other. The read API suggests such
// pairs (ListTransfers); the owner confirms or rejects each one in the
// built-in UI, which hands the decision to the core through TransferService:
// one owner-only service for this kind of entry (D-79). The ledger stores
// each decision append-only; a later decision on the same pair supersedes
// it (D-18). Only confirmed transfers are left out of the time-weighted
// return's cash flows.
//
// Calling conventions are the AuthService's
// (proto/openfief/identity/v1/auth.proto), as in model.proto:
// - Every call carries the view plugin's projected ServiceAccount token
//   (audience openfief-core, D-27) as "Authorization: Bearer <token>"; a
//   call without one, or from a plugin that is not a view plugin, fails
//   with PERMISSION_DENIED.
// - Every request carries origin and the owner's session_token. A missing,
//   unknown, expired or revoked session fails with UNAUTHENTICATED; a
//   read-scoped session, or an origin off the core's allow-list, fails with
//   PERMISSION_DENIED.
// - A pair whose legs are not a withdrawal and a deposit of exactly the same
//   amount and currency in different accounts, at most five calendar days
//   apart, neither opening cash, fails with INVALID_ARGUMENT; a key with no
//   stored transaction fails with NOT_FOUND; confirming a leg of another
//   confirmed transfer fails with FAILED_PRECONDITION. Nothing is stored then.

