// OpenFief's cash checkpoint contract (docs/DESIGN.md D-158, D-79).
//
// The owner enters the cash an institution shows for an account on a date,
// such as the bond registry's or a bank's. The core stores it as a balance
// assertion (D-18) and checks it against the cash derived from the
// transaction log, which it never changes. A mismatch raises an attention
// item (D-130); from it the owner books the difference as an ordinary
// manual transaction: a deposit when the institution shows more cash, a
// withdrawal when it shows less, so an unexplained difference never shows
// as return. One owner-only service for this kind of entry (D-79).
//
// Calling conventions are the AuthService's
// (proto/openfief/identity/v1/auth.proto), as in transfers.proto:
// - Every call carries the view plugin's projected ServiceAccount token
//   (audience openfief-core, D-27) as "Authorization: Bearer <token>"; a
//   call without one, or from a plugin that is not a view plugin, fails
//   with PERMISSION_DENIED.
// - Every request carries origin and the owner's session_token. A missing,
//   unknown, expired or revoked session fails with UNAUTHENTICATED; a
//   read-scoped session, or an origin off the core's allow-list, fails with
//   PERMISSION_DENIED.
// - A malformed date, currency or amount fails with INVALID_ARGUMENT; an
//   account or a checkpoint that is not stored with NOT_FOUND; booking the
//   difference of a checkpoint that matches with FAILED_PRECONDITION.
//   Nothing is stored then.

