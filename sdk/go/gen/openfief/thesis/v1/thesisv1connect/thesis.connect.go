// OpenFief's draft thesis contract (docs/DESIGN.md D-229, D-206, D-211).
//
// With opinions on (D-225) the Ask box's model may suggest a thesis for an
// agent on an offensive sleeve (D-71): a statement, its instruments, a
// horizon, the conditions that would invalidate it and its sources, and no
// lease size. The owner can save it as a draft thesis. Editing a draft adds a
// version and keeps the earlier ones, and every save and edit enters the audit
// log, naming the thesis and the version, never the text (GR-12). A draft has
// no agent, no fief and no lease: the control plane starts a fief from it
// later, as a proposal the owner approves.
//
// A draft thesis is the owner's alone and T1 data (D-206). It is not on the
// read API (D-137): ReadService serves none of it, so no script token, view
// plugin or demo session reads it, whatever it is granted (D-209), and a
// viewer's session is refused here. Reading it is as owner-only as changing it.
//
// The core serves ThesisService to VIEW plugins only, on its plugin port
// (D-115), as the owner's entry service for this kind of entry (D-79).
// Calling conventions are the AuthService's
// (proto/openfief/identity/v1/auth.proto):
// - Every call carries the view plugin's projected ServiceAccount token
//   (audience openfief-core, D-27) as "Authorization: Bearer <token>"; a
//   call without one, or from a plugin that is not a view plugin, fails with
//   PERMISSION_DENIED.
// - Every request carries origin and the owner's session_token. A missing,
//   unknown, expired or revoked session fails with UNAUTHENTICATED; a
//   read-scoped session, or an origin off the core's allow-list, fails with
//   PERMISSION_DENIED.
// - A draft that breaks a rule (a missing field, a horizon that is not
//   long-term or short-term, a text too long, a lease size or an amount in
//   its text) fails with INVALID_ARGUMENT; a thesis that does not exist fails
//   with NOT_FOUND; an edit of a version that is no longer the latest fails
//   with FAILED_PRECONDITION. Nothing changes then, and when the audit log
//   can't take the entry the call fails with UNAVAILABLE and changes nothing.

