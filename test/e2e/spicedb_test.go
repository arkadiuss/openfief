// SpiceDB's objects (deploy/spicedb) and the flags that switch the core to it.
const (
	spicedbDeployment = "openfief-spicedb"
	spicedbService    = "openfief-spicedb"
	// spicedbPresharedName is the Secret of the preshared key, which SpiceDB and the core read;
	// spicedbRoleName the Secret of the password of SpiceDB's role in the openfief-db cluster.
	spicedbPresharedName = "openfief-spicedb-key"
	spicedbRoleName      = "openfief-db-spicedb"
	spicedbJob           = "openfief-spicedb-secrets"
	// spicedbDatabase is the CloudNativePG Database SpiceDB's datastore is.
	spicedbDatabase = "openfief-db-spicedb"
	// authzSpiceDBFlag and authzInsecureFlag switch the core to SpiceDB, plaintext on the Service behind its policy.
	authzSpiceDBFlag  = "--authz=spicedb"
	authzInsecureFlag = "--spicedb-insecure"
	// reconciledLine is what the core logs once SpiceDB holds the schema and the relationships it owns.
	reconciledLine = "authorization reconciled with SpiceDB"
	// spicedbTimeout bounds the waits for SpiceDB and the core to follow each change the test makes.
	spicedbTimeout = 5 * time.Minute
	// minGenerated is the shortest credential the Job may have generated, in bytes.
	minGenerated = 32
)

// errNoRoleStatus reports a cluster whose status doesn't list SpiceDB's role as reconciled.
var errNoRoleStatus = errors.New("CloudNativePG hasn't reconciled the role spicedb")

// errNoCoreContainer reports a core Deployment without the container the test changes.
var errNoCoreContainer = errors.New("the core Deployment has no container")

// cnpgDatabase is CloudNativePG's Database resource.
func cnpgDatabase() schema.GroupVersionResource {
	return schema.GroupVersionResource{Group: "postgresql.cnpg.io", Version: "v1", Resource: "databases"}
}

// TestSpiceDBDeployed checks that SpiceDB runs from the install (D-164): its
// credentials were generated by the Job, its database and role exist in the
// openfief-db cluster, its pod is hardened and pinned by digest, and neither
// it nor the core logs the preshared key or the role's password
// (SCEN-e2e-spicedb-deployed).
func TestSpiceDBDeployed(t *testing.T) {
	t.Parallel()
	k := mustConnect(t)
	diagnoseOnFailure(t, k)
	waitSpiceDBAvailable(t, k)
	waitJobComplete(t, k, spicedbJob)

	key := secretValue(t, k, spicedbPresharedName, "key")
	password := secretValue(t, k, spicedbRoleName, "password")
	for name, value := range map[string][]byte{spicedbPresharedName: key, spicedbRoleName: password} {
		if len(value) < minGenerated {
			t.Errorf("Secret %s: the generated value has %d bytes, want at least %d", name, len(value), minGenerated)
		}
	}
	if user := secretValue(t, k, spicedbRoleName, "username"); string(user) != "spicedb" {
		t.Errorf("Secret %s: username %q, want spicedb", spicedbRoleName, user)
	}
	if bytes.Equal(key, password) {
		t.Errorf("Secrets %s and %s hold the same value", spicedbPresharedName, spicedbRoleName)
	}

	waitSpiceDBDatabase(t, k)
	d, err := k.clients.AppsV1().Deployments(namespace).Get(t.Context(), spicedbDeployment, metav1.GetOptions{})
	if err != nil {
		t.Fatalf("getting Deployment %s: %v", spicedbDeployment, err)
	}
	checkSpiceDBPod(t, &d.Spec.Template.Spec)

	for _, app := range []string{spicedbDeployment, coreDeployment} {
		logs := podLogs(t.Context(), t, k, app)
		for name, value := range map[string][]byte{spicedbPresharedName: key, spicedbRoleName: password} {
			if bytes.Contains(logs, value) {
				t.Errorf("the log of %s holds the value of Secret %s", app, name)
			}
		}
	}
}

// waitSpiceDBAvailable waits until SpiceDB's Deployment is available: its
// migration ran against the datastore and its health service answers. A pod
// waits for the Secrets the Job makes and starts by itself, so its state
// while it waits is a state, not a failure.
func waitSpiceDBAvailable(t *testing.T, k *kube) {
	t.Helper()
	err := waitFor(t.Context(), spicedbTimeout, k.deploymentAvailable(namespace, spicedbDeployment))
	if err != nil {
		t.Fatalf("waiting for the SpiceDB Deployment to be available: %v", err)
	}
}

// waitJobComplete waits until Job name in the openfief namespace completes.
func waitJobComplete(t *testing.T, k *kube, name string) {
	t.Helper()
	err := waitFor(t.Context(), spicedbTimeout, func(ctx context.Context) (string, bool, error) {
		j, err := k.clients.BatchV1().Jobs(namespace).Get(ctx, name, metav1.GetOptions{})
		if err != nil {
			return "", false, fmt.Errorf("%w: %w", errRetry, err)
		}
		done, jobErr := jobFinished(j)
		return fmt.Sprintf("%d failed attempts", j.Status.Failed), done, jobErr
	})
	if err != nil {
		t.Fatalf("waiting for Job %s: %v", name, err)
	}
}

// secretValue returns the value of key in Secret name, failing t without it.
// A value never reaches a message.
func secretValue(t *testing.T, k *kube, name, key string) []byte {
	t.Helper()
	s, err := k.clients.CoreV1().Secrets(namespace).Get(t.Context(), name, metav1.GetOptions{})
	if err != nil {
		t.Fatalf("getting Secret %s: %v", name, err)
	}
	v, ok := s.Data[key]
	if !ok || len(v) == 0 {
		t.Fatalf("Secret %s has no key %s", name, key)
	}
	return v
}

// waitSpiceDBDatabase waits until CloudNativePG applied the Database spicedb
// and reconciled the role spicedb of the openfief-db cluster.
func waitSpiceDBDatabase(t *testing.T, k *kube) {
	t.Helper()
	err := waitFor(t.Context(), spicedbTimeout, func(ctx context.Context) (string, bool, error) {
		db, err := k.dynamic.Resource(cnpgDatabase()).Namespace(namespace).Get(ctx, spicedbDatabase, metav1.GetOptions{})
		if err != nil {
			return "", false, fmt.Errorf("%w: %w", errRetry, err)
		}
		applied, _, err := unstructured.NestedBool(db.Object, "status", "applied")
		if err != nil {
			return "", false, fmt.Errorf("the Database's status: %w", err)
		}
		if !applied {
			return "the database isn't applied", false, nil
		}
		cluster, err := k.dynamic.Resource(cnpgCluster()).Namespace(namespace).Get(ctx, "openfief-db", metav1.GetOptions{})
		if err != nil {
			return "", false, fmt.Errorf("%w: %w", errRetry, err)
		}
		reconciled, _, err := unstructured.NestedStringSlice(cluster.Object, "status", "managedRolesStatus", "byStatus", "reconciled")
		if err != nil {
			return "", false, fmt.Errorf("the cluster's managed roles' status: %w", err)
		}
		if !slices.Contains(reconciled, "spicedb") {
			return errNoRoleStatus.Error(), false, nil
		}
		return "applied", true, nil
	})
	if err != nil {
		t.Fatalf("waiting for SpiceDB's database and role: %v", err)
	}
}

// checkSpiceDBPod checks what SpiceDB's pod must be: one container and one
// init container, both pinned by tag and digest, non-root with a read-only
// root filesystem and no capabilities, no API token, and the preshared key
// and the password from Secrets, never literals.
func checkSpiceDBPod(t *testing.T, spec *corev1.PodSpec) {
	t.Helper()
	if spec.AutomountServiceAccountToken == nil || *spec.AutomountServiceAccountToken {
		t.Error("SpiceDB's pod mounts a ServiceAccount token")
	}
	if sc := spec.SecurityContext; sc == nil || sc.RunAsNonRoot == nil || !*sc.RunAsNonRoot {
		t.Error("SpiceDB's pod may run as root")
	}
	if len(spec.Containers) != 1 || len(spec.InitContainers) != 1 {
		t.Fatalf("SpiceDB's pod has %d containers and %d init containers, want 1 and 1", len(spec.Containers), len(spec.InitContainers))
	}
	containers := slices.Concat(spec.InitContainers, spec.Containers)
	for i := range containers {
		checkSpiceDBContainer(t, &containers[i])
	}
	checkCredentialsFromSecrets(t, spec.Containers[0].Env)
}

// checkCredentialsFromSecrets checks that the preshared key and the role's
// password in env come from Secrets, never as literals.
func checkCredentialsFromSecrets(t *testing.T, env []corev1.EnvVar) {
	t.Helper()
	for i := range env {
		e := &env[i]
		fromSecret := e.Value == "" && e.ValueFrom != nil && e.ValueFrom.SecretKeyRef != nil
		if (e.Name == "SPICEDB_GRPC_PRESHARED_KEY" || e.Name == "SPICEDB_DB_PASSWORD") && !fromSecret {
			t.Errorf("%s isn't read from a Secret", e.Name)
		}
	}
}

// checkSpiceDBContainer checks one container of SpiceDB's pod: pinned by tag
// and digest, read-only without privilege escalation or capabilities, and
// with a memory request and limit.
func checkSpiceDBContainer(t *testing.T, c *corev1.Container) {
	t.Helper()
	if !strings.Contains(c.Image, ":v") || !strings.Contains(c.Image, "@sha256:") {
		t.Errorf("container %s runs %s, want a tag and a digest", c.Name, c.Image)
	}
	if !hardened(c.SecurityContext) {
		t.Errorf("container %s isn't read-only without privilege escalation and capabilities", c.Name)
	}
	if c.Resources.Limits.Memory().IsZero() || c.Resources.Requests.Memory().IsZero() {
		t.Errorf("container %s has no memory request and limit", c.Name)
	}
}

// hardened reports whether sc makes the root filesystem read-only, forbids
// privilege escalation and drops every capability.
func hardened(sc *corev1.SecurityContext) bool {
	if sc == nil || sc.ReadOnlyRootFilesystem == nil || sc.AllowPrivilegeEscalation == nil || sc.Capabilities == nil {
		return false
	}
	return *sc.ReadOnlyRootFilesystem && !*sc.AllowPrivilegeEscalation && slices.Equal(sc.Capabilities.Drop, []corev1.Capability{"ALL"})
}

// podLogs returns the logs of every container of every pod labelled app.
func podLogs(ctx context.Context, t *testing.T, k *kube, app string) []byte {
	t.Helper()
	pods, err := k.clients.CoreV1().Pods(namespace).List(ctx, metav1.ListOptions{LabelSelector: appLabel + "=" + app})
	if err != nil {
		t.Fatalf("listing %s pods: %v", app, err)
	}
	var all []byte
	for i := range pods.Items {
		p := &pods.Items[i]
		containers := slices.Concat(p.Spec.InitContainers, p.Spec.Containers)
		for j := range containers {
			out, err := k.clients.CoreV1().Pods(namespace).GetLogs(p.Name, &corev1.PodLogOptions{Container: containers[j].Name}).DoRaw(ctx)
			if err != nil {
				t.Logf("the log of %s/%s isn't readable yet: %v", p.Name, containers[j].Name, err)
				continue
			}
			all = append(all, out...)
		}
	}
	return all
}

// TestSpiceDBFailsClosed switches the core to SpiceDB and checks, with a
// script token that has no grant, that SpiceDB is what answers; then stops
// SpiceDB, and checks that the core refuses instead of answering from anywhere
// else; then starts it and checks that the core answers again; and finally
// returns the core to the demo's policy (SCEN-e2e-spicedb-down-fails-closed,
// D-164).
//
// It is not parallel, on purpose: it restarts the core, so Go runs it before
// any parallel test starts and it leaves the demo's configuration as it
// found it. The owner's own refusal and view of every account are the
// contract test's (task test:authz): a script token is the caller the suite
// has without a browser, and SpiceDB grants none until the owner's grants
// exist (D-209), which is the point: the token that the policy lets view every
// account views none under SpiceDB.
//
//nolint:paralleltest // see above: the test restarts the core, so it is the one that must run alone
func TestSpiceDBFailsClosed(t *testing.T) {
	k := mustConnect(t)
	diagnoseOnFailure(t, k)
	waitCoreAvailable(t, k)
	waitSeedComplete(t, k)
	waitSpiceDBAvailable(t, k)
	token := issueToken(t, k)

	// Whatever happens, leave SpiceDB running and the core on the policy.
	t.Cleanup(func() {
		ctx, cancel := context.WithTimeout(context.WithoutCancel(t.Context()), spicedbTimeout)
		defer cancel()
		if err := scaleDeployment(ctx, k, spicedbDeployment, 1); err != nil {
			t.Logf("restoring SpiceDB: %v", err)
		}
		if err := setCoreAuthz(ctx, k, false); err != nil {
			t.Logf("returning the core to the policy: %v", err)
		}
	})

	anyAccounts := func([]string) bool { return true }
	someAccounts := func(ids []string) bool { return len(ids) > 0 }
	want := demoAccountIDs()
	if got := waitAccounts(t, k, token, someAccounts); !slices.Equal(got, want) {
		t.Fatalf("with the policy the token lists %v, want the demo accounts %v", got, want)
	}

	if err := setCoreAuthz(t.Context(), k, true); err != nil {
		t.Fatalf("switching the core to SpiceDB: %v", err)
	}
	waitLogLine(t, k, coreDeployment, reconciledLine)
	// SpiceDB holds no grant for the token, so it views nothing; under the policy it viewed every account.
	if got := waitAccounts(t, k, token, anyAccounts); len(got) != 0 {
		t.Fatalf("with SpiceDB and no grant the token lists %v, want nothing", got)
	}

	stopSpiceDBAndExpectRefusal(t, k, token)

	if err := scaleDeployment(t.Context(), k, spicedbDeployment, 1); err != nil {
		t.Fatalf("starting SpiceDB: %v", err)
	}
	waitSpiceDBAvailable(t, k)
	// SpiceDB's relationships are in PostgreSQL, so nothing is lost: the core answers again, from them.
	if got := waitAccounts(t, k, token, anyAccounts); len(got) != 0 {
		t.Fatalf("after SpiceDB came back the token lists %v, want nothing", got)
	}

	if err := setCoreAuthz(t.Context(), k, false); err != nil {
		t.Fatalf("returning the core to the policy: %v", err)
	}
	if got := waitAccounts(t, k, token, someAccounts); !slices.Equal(got, want) {
		t.Fatalf("with the policy again the token lists %v, want the demo accounts %v", got, want)
	}
}

// stopSpiceDBAndExpectRefusal stops SpiceDB and waits for the core to refuse
// the read API with a server error, never an answer, while the core itself
// still runs.
func stopSpiceDBAndExpectRefusal(t *testing.T, k *kube, token string) {
	t.Helper()
	if err := scaleDeployment(t.Context(), k, spicedbDeployment, 0); err != nil {
		t.Fatalf("stopping SpiceDB: %v", err)
	}
	err := waitFor(t.Context(), spicedbTimeout, func(ctx context.Context) (string, bool, error) {
		r, callErr := call(ctx, k, clientPod, "/v1/accounts", token)
		if callErr != nil {
			return "", false, fmt.Errorf("%w: %w", errRetry, callErr)
		}
		return fmt.Sprintf("HTTP %d", r.status), r.status >= http.StatusInternalServerError, nil
	})
	if err != nil {
		t.Fatalf("waiting for the core to refuse the read API with SpiceDB stopped: %v", err)
	}
	if r := answerFrom(t, k, clientPod, "/healthz"); r.status != http.StatusOK {
		t.Errorf("GET /healthz with SpiceDB stopped: status %d, want 200: the core runs, it only refuses to answer for accounts", r.status)
	}
}

// waitAccounts calls GET /v1/accounts with token until the answer is 200 and
// accept takes the account IDs it lists, and returns them, sorted.
func waitAccounts(t *testing.T, k *kube, token string, accept func([]string) bool) []string {
	t.Helper()
	var ids []string
	err := waitFor(t.Context(), spicedbTimeout, func(ctx context.Context) (string, bool, error) {
		r, err := call(ctx, k, clientPod, "/v1/accounts", token)
		if err != nil {
			return "", false, fmt.Errorf("%w: %w", errRetry, err)
		}
		if r.status != http.StatusOK {
			return fmt.Sprintf("HTTP %d", r.status), false, nil
		}
		var accounts viewsv1.ListAccountsResponse
		if err := protojson.Unmarshal(r.body, &accounts); err != nil {
			return "", false, fmt.Errorf("decoding the accounts: %w", err)
		}
		ids = ids[:0]
		for _, a := range accounts.GetAccounts() {
			ids = append(ids, a.GetId())
		}
		slices.Sort(ids)
		return fmt.Sprintf("%d accounts", len(ids)), accept(ids), nil
	})
	if err != nil {
		t.Fatalf("waiting for the read API's accounts: %v", err)
	}
	return slices.Clone(ids)
}

// waitLogLine waits until a pod labelled app logs a line holding text.
func waitLogLine(t *testing.T, k *kube, app, text string) {
	t.Helper()
	err := waitFor(t.Context(), spicedbTimeout, func(ctx context.Context) (string, bool, error) {
		return "not logged yet", bytes.Contains(podLogs(ctx, t, k, app), []byte(text)), nil
	})
	if err != nil {
		t.Fatalf("waiting for %s to log %q: %v", app, text, err)
	}
}

// scaleDeployment sets Deployment name's replicas and waits until that many
// pods run, or none do.
func scaleDeployment(ctx context.Context, k *kube, name string, replicas int32) error {
	deployments := k.clients.AppsV1().Deployments(namespace)
	d, err := deployments.Get(ctx, name, metav1.GetOptions{})
	if err != nil {
		return fmt.Errorf("getting Deployment %s: %w", name, err)
	}
	d.Spec.Replicas = &replicas
	if _, err := deployments.Update(ctx, d, metav1.UpdateOptions{FieldManager: fieldManager}); err != nil {
		return fmt.Errorf("scaling Deployment %s: %w", name, err)
	}
	return waitRolledOut(ctx, k, name)
}

// setCoreAuthz adds or removes --authz=spicedb and --spicedb-insecure in the
// core's arguments, and waits for the core to roll out. Without them the core
// runs on the policy, the demo's default.
func setCoreAuthz(ctx context.Context, k *kube, spicedb bool) error {
	deployments := k.clients.AppsV1().Deployments(namespace)
	d, err := deployments.Get(ctx, coreDeployment, metav1.GetOptions{})
	if err != nil {
		return fmt.Errorf("getting Deployment %s: %w", coreDeployment, err)
	}
	i := slices.IndexFunc(d.Spec.Template.Spec.Containers, func(c corev1.Container) bool { return c.Name == "core" })
	if i < 0 {
		return fmt.Errorf("%w: core", errNoCoreContainer)
	}
	c := &d.Spec.Template.Spec.Containers[i]
	c.Args = slices.DeleteFunc(c.Args, func(a string) bool { return strings.HasPrefix(a, "--authz=") || a == authzInsecureFlag })
	if spicedb {
		c.Args = append(c.Args, authzSpiceDBFlag, authzInsecureFlag)
	}
	if _, err := deployments.Update(ctx, d, metav1.UpdateOptions{FieldManager: fieldManager}); err != nil {
		return fmt.Errorf("changing Deployment %s: %w", coreDeployment, err)
	}
	return waitRolledOut(ctx, k, coreDeployment)
}

// waitRolledOut waits until Deployment name has rolled out its latest
// template and runs exactly its replicas, all available: no old pod is left,
// and a Deployment scaled to zero has no pod.
func waitRolledOut(ctx context.Context, k *kube, name string) error {
	err := waitFor(ctx, spicedbTimeout, func(ctx context.Context) (string, bool, error) {
		d, err := k.clients.AppsV1().Deployments(namespace).Get(ctx, name, metav1.GetOptions{})
		if err != nil {
			return "", false, fmt.Errorf("%w: %w", errRetry, err)
		}
		return rolloutState(d), rolledOut(d), nil
	})
	if err != nil {
		return fmt.Errorf("waiting for Deployment %s to roll out: %w", name, err)
	}
	return nil
}

// rolledOut reports whether d runs its latest template on exactly its
// replicas, all available.
func rolledOut(d *appsv1.Deployment) bool {
	want := int32(1)
	if d.Spec.Replicas != nil {
		want = *d.Spec.Replicas
	}
	s := &d.Status
	return s.ObservedGeneration >= d.Generation && s.Replicas == want && s.UpdatedReplicas == want && s.AvailableReplicas == want
}

// rolloutState describes d's rollout in words.
func rolloutState(d *appsv1.Deployment) string {
	s := &d.Status
	return fmt.Sprintf("generation %d of %d observed; %d replicas, %d updated, %d available", s.ObservedGeneration, d.Generation, s.Replicas, s.UpdatedReplicas, s.AvailableReplicas)
}

// spicedbProbes are the connections to SpiceDB's gRPC port that the
// NetworkPolicies must refuse: from the XTB and NBP FX plugin pods, from the
// two client pods and the outsider, none connects; from the core's pod, the
// one pod admitted, one does (D-164, D-184). The core's probe shows that the
// refusals are the policy's and not an address that leads nowhere.
func spicedbProbes(env *isolation) []probeCase {
	to := func(name string, from probeAt, want outcome) probeCase {
		return probeCase{name: name, from: from, args: []string{"--http2-prior-knowledge", env.spicedb + "/"}, want: want}
	}
	return []probeCase{
		to("XTB pod to SpiceDB", env.xtb, noConnection()),
		to("NBP FX pod to SpiceDB", env.egress, noConnection()),
		to("NBP FX pod, granted another Service, to SpiceDB", env.private, noConnection()),
		to("client pod to SpiceDB", env.client, noConnection()),
		to("outsider to SpiceDB", env.outsider, noConnection()),
		to("core pod to SpiceDB", env.core, connected()),
	}
}

// connected is a probe that opened a TCP connection, whatever the server
// answered: SpiceDB's gRPC server doesn't answer curl's plain request as a
// web page.
func connected() outcome {
	return outcome{desc: "a TCP connection", ok: func(r probeResult) bool {
		return !dnsFailed(r) && !slices.Contains([]int{curlCouldntConnect, curlTimedOut}, r.exit)
	}}
}
